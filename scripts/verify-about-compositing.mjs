import { chromium } from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const out = 'screenshots/about_compositing';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const results = [];
for (const [width, height] of [[1536,1024],[390,844],[1920,1080],[1366,768],[1024,768],[768,1024],[320,568]]) {
  const context = await browser.newContext({ viewport: {width,height}, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4173/?audit=about');
  await page.waitForTimeout(2500);
  await page.evaluate(() => { document.documentElement.style.scrollBehavior='auto'; window.scrollTo(0, document.querySelector('#about').offsetTop - 76); });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${out}/${width}x${height}.png` });
  if(width === 390) await page.locator('#about').screenshot({path:`${out}/mobile-full-section.png`});
  const layout = await page.evaluate(() => {
    const rect = s => { const r=document.querySelector(s).getBoundingClientRect(); return {x:r.x,y:r.y,width:r.width,height:r.height,right:r.right}; };
    return { overflow:document.documentElement.scrollWidth>innerWidth, scene:rect('.about-center-corridor'), left:rect('.about-intro-block'), right:rect('.about-right-col'), canvas:rect('.about-platform-scene-wrapper canvas') };
  });
  const download = page.waitForEvent('download');
  await page.locator('.about-resume-btn').click();
  const resume = (await download).suggestedFilename();
  const audit = await page.locator('.about-platform-scene-wrapper canvas').evaluate(el => JSON.parse(el.dataset.aboutAudit));
  await page.waitForTimeout(500);
  const after = await page.locator('.about-platform-scene-wrapper canvas').evaluate(el => JSON.parse(el.dataset.aboutAudit));
  assert.equal(audit.inFrame, true, `Scene bounds at ${width}`);
  assert.equal(audit.feetY, audit.daisY);
  assert.equal(after.ring, audit.ring, 'Reduced motion must stop rings');
  assert.equal(after.crystalY, audit.crystalY, 'Reduced motion must stop float');
  assert.equal(layout.overflow, false);
  assert.deepEqual(errors, []);
  results.push({width,height,errors,layout,resume,audit});
  await context.close();
}
fs.writeFileSync(`${out}/results.json`,JSON.stringify(results,null,2));
const context = await browser.newContext({viewport:{width:1536,height:1024},recordVideo:{dir:out,size:{width:1536,height:1024}}});
const page = await context.newPage();
await page.goto('http://127.0.0.1:4173/?isolate=about3d&audit=about#about');
await page.waitForTimeout(4000);
await page.locator('#about').scrollIntoViewIfNeeded();
await page.waitForTimeout(1500);
await page.screenshot({path:`${out}/isolated.png`});
const before = await page.locator('.about-platform-scene-wrapper canvas').evaluate(el => JSON.parse(el.dataset.aboutAudit));
await page.waitForTimeout(8000);
const after = await page.locator('.about-platform-scene-wrapper canvas').evaluate(el => JSON.parse(el.dataset.aboutAudit));
assert.deepEqual(after.foundation, before.foundation);
assert.deepEqual(after.foundationRotation, before.foundationRotation);
assert.equal(after.feetY, before.feetY);
assert.notEqual(after.ring, before.ring);
assert.equal(after.inFrame, true);
fs.writeFileSync(`${out}/motion-results.json`, JSON.stringify({before,after},null,2));
const video = page.video();
await context.close();
await video.saveAs(`${out}/grounded-rings.webm`);
await browser.close();
fs.writeFileSync(`${out}/results.json`,JSON.stringify(results,null,2));
